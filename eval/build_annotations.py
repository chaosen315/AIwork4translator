"""Validate (and refresh) the terminology annotations of the issue #44 eval set.

The dataset is generated by generate_dataset.py: each glossary has ~1,200 entries
but only the ~30-40 anchor terms appear in the document. This script

* re-counts each annotated term's occurrences in the generated document,
* fails when an annotated term is missing from the document or the glossary,
* reports glossary size vs annotated terms (decoys are expected to be absent).

Run:
    python eval/build_annotations.py
"""

from __future__ import annotations

import csv
import json
import re
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parent
DOC_DIR = EVAL_DIR / "documents"
GLOSSARY_DIR = EVAL_DIR / "glossaries"
ANNOTATION_DIR = EVAL_DIR / "annotations"

DOCS = ["technical_doc", "rulebook", "novel"]


def load_glossary(path: Path) -> dict[str, str]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return {
            (row.get("term") or "").strip(): (row.get("translation") or "").strip()
            for row in csv.DictReader(handle)
            if (row.get("term") or "").strip()
        }


def count_occurrences(text: str, term: str) -> int:
    pattern = re.compile(r"(?<![A-Za-z0-9])" + re.escape(term) + r"(?![A-Za-z0-9])", re.IGNORECASE)
    return len(pattern.findall(text))


def main() -> int:
    failures = []
    for doc in DOCS:
        doc_path = DOC_DIR / (doc + ".md")
        glossary = load_glossary(GLOSSARY_DIR / (doc + ".csv"))
        annotations = json.loads((ANNOTATION_DIR / (doc + ".json")).read_text(encoding="utf-8"))
        text = doc_path.read_text(encoding="utf-8")

        total = 0
        for item in annotations["terms"]:
            term = item["term"]
            if term not in glossary:
                failures.append("%s: annotated term not in glossary: %s" % (doc, term))
                continue
            if glossary[term] != item["translation"]:
                failures.append("%s: translation mismatch for %s" % (doc, term))
            occurrences = count_occurrences(text, term)
            if occurrences != item["occurrences"]:
                failures.append(
                    "%s: occurrence mismatch for %s: file=%d recount=%d"
                    % (doc, term, item["occurrences"], occurrences)
                )
            total += occurrences

        if total != annotations["total_occurrences"]:
            failures.append("%s: total occurrences mismatch %d != %d" % (doc, total, annotations["total_occurrences"]))
        annotations["total_occurrences"] = total
        annotations["glossary_size"] = len(glossary)
        annotations["document_words"] = len(text.split())
        (ANNOTATION_DIR / (doc + ".json")).write_text(
            json.dumps(annotations, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        print(
            "%s: glossary=%d, annotated=%d, occurrences=%d, words=%d"
            % (doc, len(glossary), len(annotations["terms"]), total, len(text.split()))
        )

    if failures:
        print("FAILURES:")
        for item in failures:
            print("  -", item)
        return 1
    print("annotations OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
